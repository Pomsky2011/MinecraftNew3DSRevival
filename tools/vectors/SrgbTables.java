// Writes crates/assets/src/srgb_tables.rs: the sRGB <-> linear lookup tables 1.21.11's mipmapping
// averages through, computed in Java's float and double arithmetic so they match it to the bit.
// Run from the repository root:
//   java tools/vectors/SrgbTables.java > crates/assets/src/srgb_tables.rs

public class SrgbTables {
    // The standard sRGB transfer functions, in the arithmetic net.minecraft.util.ARGB uses.
    static float toLinear(float f) {
        return f >= 0.04045F ? (float) Math.pow((f + 0.055) / 1.055, 2.4) : f / 12.92F;
    }

    static float toSrgb(float f) {
        return f >= 0.0031308F ? (float) (1.055 * Math.pow(f, 0.4166666666666667) - 0.055) : 12.92F * f;
    }

    public static void main(String[] args) {
        System.out.println("//! Generated by tools/vectors/SrgbTables.java on Java " + System.getProperty("java.version") + "; don't edit.");
        System.out.println("//! sRGB 8-bit to linear 10-bit, and back, as 1.21.11's mipmapping rounds them.");
        System.out.println();
        System.out.print("pub const SRGB_TO_LINEAR: [u16; 256] = [");
        for (int i = 0; i < 256; i++) {
            System.out.print((i % 16 == 0 ? "\n    " : " ") + Math.round(toLinear(i / 255.0F) * 1023.0F) + ",");
        }
        System.out.println("\n];");
        System.out.println();
        System.out.print("pub const LINEAR_TO_SRGB: [u8; 1024] = [");
        for (int i = 0; i < 1024; i++) {
            System.out.print((i % 16 == 0 ? "\n    " : " ") + (Math.round(toSrgb(i / 1023.0F) * 255.0F) & 0xFF) + ",");
        }
        System.out.println("\n];");
    }
}
