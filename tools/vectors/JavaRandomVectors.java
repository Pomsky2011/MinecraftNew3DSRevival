// Writes test vectors for n3dsr-core's JavaRandom from the JDK's own java.util.Random.
// Run from the repository root:
//   java tools/vectors/JavaRandomVectors.java > crates/core/tests/data/java_random.txt
//
// One line per call: `<seed> <method> <argument> <result>`, the argument `-` where there is none.
// Floats and doubles are written as their raw bits, in hex, so the comparison is exact.

import java.util.Random;

public class JavaRandomVectors {
    static final long[] SEEDS = {
        0L, 1L, -1L, 42L, 12345L, -4172144997902289642L, Long.MAX_VALUE, Long.MIN_VALUE,
        0x5DEECE66DL, 8091867987493326313L,
    };
    // Powers of two take a shortcut; 0x40000001 and Integer.MAX_VALUE are where rejection is likeliest.
    static final int[] BOUNDS = {1, 2, 3, 7, 10, 16, 100, 1000, 1 << 20, 0x40000001, Integer.MAX_VALUE};
    static final int CALLS = 20;

    public static void main(String[] args) {
        System.out.println("# Generated by tools/vectors/JavaRandomVectors.java on Java " + System.getProperty("java.version"));
        for (long seed : SEEDS) {
            Random r = new Random(seed);
            for (int i = 0; i < CALLS; i++) {
                line(seed, "nextInt", "-", Integer.toString(r.nextInt()));
                for (int bound : BOUNDS) {
                    line(seed, "nextIntBounded", Integer.toString(bound), Integer.toString(r.nextInt(bound)));
                }
                line(seed, "nextLong", "-", Long.toString(r.nextLong()));
                line(seed, "nextBoolean", "-", Boolean.toString(r.nextBoolean()));
                line(seed, "nextFloat", "-", Integer.toHexString(Float.floatToRawIntBits(r.nextFloat())));
                line(seed, "nextDouble", "-", Long.toHexString(Double.doubleToRawLongBits(r.nextDouble())));
            }
        }
    }

    static void line(long seed, String method, String arg, String result) {
        System.out.println(seed + " " + method + " " + arg + " " + result);
    }
}
